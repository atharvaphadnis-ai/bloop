// infrastructure/docker-manager.js — optional Docker integrations: detects
// the docker binary, reports status of Bloop-related containers, and
// generates docker-compose provider snippets. Every operation fails with a
// clear message when Docker is not present — never a fake success.
import { execFile } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import { promisify } from 'node:util';
import { badRequest } from '../core/error-handler.js';

const execFileP = promisify(execFile);

const PROVIDER_SERVICES = {
  postgres: {
    image: 'postgres:16-alpine',
    env: ['POSTGRES_USER=bloop', 'POSTGRES_PASSWORD=change-me', 'POSTGRES_DB=bloop'],
    port: '5432:5432',
    volume: 'pgdata:/var/lib/postgresql/data',
    healthcheck: ['CMD-SHELL', 'pg_isready -U bloop'],
  },
  mysql: {
    image: 'mysql:8',
    env: ['MYSQL_ROOT_PASSWORD=change-me', 'MYSQL_DATABASE=bloop', 'MYSQL_USER=bloop', 'MYSQL_PASSWORD=change-me'],
    port: '3306:3306',
    volume: 'mysqldata:/var/lib/mysql',
    healthcheck: ['CMD', 'mysqladmin', 'ping', '-h', 'localhost'],
  },
  mariadb: {
    image: 'mariadb:11',
    env: ['MYSQL_ROOT_PASSWORD=change-me', 'MYSQL_DATABASE=bloop', 'MYSQL_USER=bloop', 'MYSQL_PASSWORD=change-me'],
    port: '3307:3306',
    volume: 'mariadbdata:/var/lib/mysql',
    healthcheck: ['CMD', 'healthcheck.sh', '--connect', '--innodb_initialized'],
  },
  mongodb: {
    image: 'mongo:7',
    env: [],
    port: '27017:27017',
    volume: 'mongodata:/data/db',
    healthcheck: ['CMD', 'mongosh', '--eval', 'db.adminCommand("ping")'],
  },
  minio: {
    image: 'minio/minio:latest',
    env: ['MINIO_ROOT_USER=bloopadmin', 'MINIO_ROOT_PASSWORD=change-me-too'],
    port: '9000:9000',
    volume: 'miniodata:/data',
    command: 'server /data',
    healthcheck: ['CMD', 'mc', 'ready', 'local'],
  },
  badger: {
    build: './badger-sidecar',
    port: '8089:8089',
    volume: 'badgerdata:/data/badger',
    healthcheck: ['CMD-SHELL', 'wget -qO- http://localhost:8089/health || exit 1'],
  },
};

export class DockerManager {
  constructor(ctx) {
    this.ctx = ctx;
    this.log = ctx.log.child({ source: 'docker' });
  }

  async available() {
    try {
      const { stdout } = await execFileP('docker', ['version', '--format', '{{.Server.Version}}'], { timeout: 5000 });
      return { ok: true, version: stdout.trim() };
    } catch (err) {
      return { ok: false, reason: 'docker CLI not found or daemon not running — provider services must be hosted elsewhere (see docs/docker.md)' };
    }
  }

  async status() {
    const avail = await this.available();
    if (!avail.ok) return { ...avail, containers: [] };
    try {
      const { stdout } = await execFileP('docker', ['ps', '--format', '{{.Names}}\t{{.Image}}\t{{.Status}}\t{{.Ports}}'], { timeout: 8000 });
      const containers = stdout.trim().split('\n').filter(Boolean).map((line) => {
        const [name, image, status, ports] = line.split('\t');
        return { name, image, status, ports };
      });
      return { ok: true, version: avail.version, containers };
    } catch (err) {
      return { ok: false, reason: err.message, containers: [] };
    }
  }

  async generateCompose(services = ['sqlite-none']) {
    const wanted = services.filter((s) => PROVIDER_SERVICES[s]);
    if (!wanted.length) {
      throw badRequest(`No valid services requested. Available: ${Object.keys(PROVIDER_SERVICES).join(', ')}`);
    }
    const lines = [
      '# Generated by Bloop — provider database services',
      '# Usage: docker compose -f docker/generated-compose.yml up -d',
      'services:',
    ];
    const volumes = [];
    for (const s of wanted) {
      const spec = PROVIDER_SERVICES[s];
      lines.push(`  ${s}:`);
      lines.push(`    image: ${spec.image}`);
      if (spec.build) lines.push(`    build: ${spec.build}`);
      if (spec.command) lines.push(`    command: ${spec.command}`);
      lines.push(`    ports:`);
      lines.push(`      - "${spec.port}"`);
      if (spec.env?.length) {
        lines.push(`    environment:`);
        for (const e of spec.env) lines.push(`      - ${e}`);
      }
      if (spec.volume) {
        lines.push(`    volumes:`);
        lines.push(`      - ${spec.volume}`);
        volumes.push(spec.volume.split(':')[0]);
      }
      if (spec.healthcheck) {
        lines.push(`    healthcheck:`);
        lines.push(`      test: [${JSON.stringify(spec.healthcheck[0])}, ...]`);
      }
      lines.push(`    restart: unless-stopped`);
    }
    if (volumes.length) {
      lines.push(`volumes:`);
      for (const v of [...new Set(volumes)]) lines.push(`  ${v}:`);
    }
    const outDir = path.join(this.ctx.rootDir, 'docker');
    fs.mkdirSync(outDir, { recursive: true });
    const outPath = path.join(outDir, 'generated-compose.yml');
    fs.writeFileSync(outPath, lines.join('\n') + '\n', 'utf8');
    return { path: outPath, services: wanted, content: lines.join('\n') };
  }
}

export async function register(ctx) {
  ctx.docker = new DockerManager(ctx);
}
